// Package apidoc derives the gallery's API reference from the library source.
package apidoc

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/doc"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// Packages maps the qualifier a gallery snippet uses to the package's
// directory under the module root.
var Packages = map[string]string{
	"mygoui": ".", "form": "form", "list": "list", "navigation": "navigation",
	"overlay": "overlay", "date": "date", "color": "color", "data": "data",
	"chart": "chart", "content": "content", "theme": "theme",
}

// Generate returns the Go source of the gallery's API table for the module
// at root: every exported struct with its doc comment and exported fields.
func Generate(root string) ([]byte, error) {
	qualifiers := make([]string, 0, len(Packages))
	for q := range Packages {
		qualifiers = append(qualifiers, q)
	}
	sort.Strings(qualifiers)

	var b bytes.Buffer
	b.WriteString("// Code generated by internal/apidoc; DO NOT EDIT.\n\npackage gallery\n\n")
	b.WriteString("// apiTypes is the exported struct API of the library, keyed by qualified name.\n")
	b.WriteString("var apiTypes = map[string]apiType{\n")
	for _, q := range qualifiers {
		if err := writePackage(&b, q, filepath.Join(root, Packages[q])); err != nil {
			return nil, err
		}
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

func writePackage(b *bytes.Buffer, qualifier, dir string) error {
	fset := token.NewFileSet()
	entries, err := os.ReadDir(dir)
	if err != nil {
		return err
	}
	var files []*ast.File
	for _, entry := range entries {
		name := entry.Name()
		if entry.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") {
			continue
		}
		file, err := parser.ParseFile(fset, filepath.Join(dir, name), nil, parser.ParseComments)
		if err != nil {
			return err
		}
		files = append(files, file)
	}
	pkg, err := doc.NewFromFiles(fset, files, qualifier)
	if err != nil {
		return err
	}
	for _, t := range pkg.Types {
		spec, ok := t.Decl.Specs[0].(*ast.TypeSpec)
		if !ok || !spec.Name.IsExported() {
			continue
		}
		st, ok := spec.Type.(*ast.StructType)
		if !ok {
			continue
		}
		fmt.Fprintf(b, "%q: {\nDoc: %q,\nFields: []apiField{\n", qualifier+"."+t.Name, oneLine(t.Doc))
		for _, field := range st.Fields.List {
			typ := typeString(fset, field.Type, qualifier)
			text := oneLine(field.Doc.Text())
			if text == "" {
				text = oneLine(field.Comment.Text())
			}
			if len(field.Names) == 0 {
				fmt.Fprintf(b, "{Name: %q, Type: %q, Doc: %q},\n", embeddedName(field.Type), typ, text)
				continue
			}
			for _, name := range field.Names {
				if name.IsExported() {
					fmt.Fprintf(b, "{Name: %q, Type: %q, Doc: %q},\n", name.Name, typ, text)
				}
			}
		}
		b.WriteString("},\n},\n")
	}
	return nil
}

// oneLine joins a doc comment's lines into one paragraph.
func oneLine(text string) string { return strings.Join(strings.Fields(text), " ") }

func embeddedName(expr ast.Expr) string {
	switch e := expr.(type) {
	case *ast.StarExpr:
		return embeddedName(e.X)
	case *ast.SelectorExpr:
		return e.Sel.Name
	case *ast.Ident:
		return e.Name
	}
	return ""
}

// typeString prints a field type as a caller writes it: exported names of
// the package itself gain its qualifier.
func typeString(fset *token.FileSet, expr ast.Expr, qualifier string) string {
	var b bytes.Buffer
	_ = printer.Fprint(&b, fset, qualify(expr, qualifier))
	return oneLine(b.String())
}

// qualify returns expr with the package's own exported type names qualified.
func qualify(expr ast.Expr, qualifier string) ast.Expr {
	switch e := expr.(type) {
	case *ast.Ident:
		if e.IsExported() {
			return &ast.SelectorExpr{X: ast.NewIdent(qualifier), Sel: ast.NewIdent(e.Name)}
		}
	case *ast.StarExpr:
		return &ast.StarExpr{X: qualify(e.X, qualifier)}
	case *ast.IndexExpr:
		return &ast.IndexExpr{X: qualify(e.X, qualifier), Index: e.Index}
	case *ast.IndexListExpr:
		return &ast.IndexListExpr{X: qualify(e.X, qualifier), Indices: e.Indices}
	case *ast.ArrayType:
		return &ast.ArrayType{Len: e.Len, Elt: qualify(e.Elt, qualifier)}
	case *ast.MapType:
		return &ast.MapType{Key: qualify(e.Key, qualifier), Value: qualify(e.Value, qualifier)}
	case *ast.Ellipsis:
		return &ast.Ellipsis{Elt: qualify(e.Elt, qualifier)}
	case *ast.FuncType:
		return &ast.FuncType{Params: qualifyFields(e.Params, qualifier), Results: qualifyFields(e.Results, qualifier)}
	}
	return expr
}

func qualifyFields(list *ast.FieldList, qualifier string) *ast.FieldList {
	if list == nil {
		return nil
	}
	out := &ast.FieldList{}
	for _, field := range list.List {
		out.List = append(out.List, &ast.Field{Names: field.Names, Type: qualify(field.Type, qualifier)})
	}
	return out
}
